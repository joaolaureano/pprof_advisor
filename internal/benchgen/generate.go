package benchgen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"text/template"
)

const harnessTemplate = `// Code generated by profadvisor benchgen; DO NOT EDIT.
// Frozen corpus: replay seeds before benchmarking. Fuzzing checks for panics only.
package {{.Target.Name}}

import {{.Testing}} "testing"

func {{.Target.FuzzName}}({{.F}} *{{.Testing}}.F) {
{{range .Seeds}} {{$.F}}.Add({{.Literal}})
{{end}}
 {{.F}}.Fuzz(func({{.T}} *{{.Testing}}.T, {{.Input}} {{.Target.InputType}}) {
  {{.Target.Function}}({{.Input}})
 })
}

func {{.Target.BenchmarkName}}({{.B}} *{{.Testing}}.B) {
{{range .Seeds}}
 {{$.B}}.Run({{.Name}}, func({{$.B}} *{{$.Testing}}.B) {
  {{$.Input}} := {{.Literal}}
  {{$.B}}.ReportAllocs()
  for {{$.B}}.Loop() {
   {{$.Target.Function}}({{$.Input}})
  }
 })
{{end}}
}
`

func generateCode(target Target, seeds []Seed) ([]byte, error) {
	if !supportedInputType(target.InputType) {
		return nil, fmt.Errorf("unsupported input type %q", target.InputType)
	}
	ident := func(base string) string {
		for base == target.Function {
			base += "_"
		}
		return base
	}
	type entry struct{ Name, Literal string }
	data := struct {
		Target                  Target
		Testing, F, T, B, Input string
		Seeds                   []entry
	}{Target: target, Testing: ident("profadvisorTesting"), F: ident("profadvisorF"), T: ident("profadvisorT"), B: ident("profadvisorB"), Input: ident("profadvisorInput")}
	ordered := append([]Seed(nil), seeds...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Hash < ordered[j].Hash })
	for _, seed := range ordered {
		literal := seed.Literal
		if literal == "" {
			literal = defaultSeedLiteral(target.InputType, seed.Data)
		}
		data.Seeds = append(data.Seeds, entry{Name: strconv.Quote(seed.Hash), Literal: literal})
	}
	tmpl, err := template.New("harness").Parse(harnessTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	code, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated harness: %w", err)
	}
	return code, nil
}

func supportedInputType(inputType string) bool {
	switch inputType {
	case "string", "[]byte", "bool", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "float32", "float64":
		return true
	}
	return false
}

func defaultSeedLiteral(inputType string, data []byte) string {
	literal := strconv.Quote(string(data))
	if inputType == "[]byte" {
		return "[]byte(" + literal + ")"
	}
	return literal
}
