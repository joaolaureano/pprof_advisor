package benchgen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"text/template"
)

const harnessTemplate = `// Code generated by profadvisor benchgen; DO NOT EDIT.
// Frozen corpus: replay seeds before benchmarking. Fuzzing checks for panics only.
package {{.Target.Name}}

import (
 {{.Testing}} "testing"
{{if .NeedsMath}} {{.Math}} "math"
{{end}})

func {{.Target.FuzzName}}({{.F}} *{{.Testing}}.F) {
{{range .Seeds}} {{$.F}}.Add({{join .Literals ", "}})
{{end}}
 {{.F}}.Fuzz(func({{.T}} *{{.Testing}}.T, {{join .Parameters ", "}}) {
  {{$.Target.Function}}({{join $.Arguments ", "}})
 })
}

func {{.Target.BenchmarkName}}({{.B}} *{{.Testing}}.B) {
{{range .Seeds}}
 {{$.B}}.Run({{.Name}}, func({{$.B}} *{{$.Testing}}.B) {
{{range $i, $literal := .Literals}}  {{index $.Arguments $i}} := {{$literal}}
{{end}}  {{$.B}}.ReportAllocs()
  for {{$.B}}.Loop() {
   {{$.Target.Function}}({{join $.Arguments ", "}})
  }
 })
{{end}}
}
`

func generateCode(target Target, seeds []Seed) ([]byte, error) {
	if len(target.InputTypes) == 0 {
		return nil, fmt.Errorf("target has no input types")
	}
	for _, inputType := range target.InputTypes {
		if !supportedInputType(inputType) {
			return nil, fmt.Errorf("unsupported input type %q", inputType)
		}
	}
	ident := func(base string) string {
		for base == target.Function {
			base += "_"
		}
		return base
	}
	arguments := make([]string, len(target.InputTypes))
	parameters := make([]string, len(target.InputTypes))
	for i, inputType := range target.InputTypes {
		arguments[i] = ident("profadvisorInput" + strconv.Itoa(i+1))
		parameters[i] = arguments[i] + " " + inputType
	}
	type entry struct {
		Name     string
		Literals []string
	}
	data := struct {
		Target                 Target
		Testing, Math, F, T, B string
		Parameters, Arguments  []string
		Seeds                  []entry
		NeedsMath              bool
	}{Target: target, Testing: ident("profadvisorTesting"), Math: ident("profadvisorMath"), F: ident("profadvisorF"), T: ident("profadvisorT"), B: ident("profadvisorB"), Parameters: parameters, Arguments: arguments}
	ordered := append([]Seed(nil), seeds...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Hash < ordered[j].Hash })
	for _, seed := range ordered {
		if len(seed.Literals) != len(target.InputTypes) {
			return nil, fmt.Errorf("seed %s has %d arguments, want %d", seed.Hash, len(seed.Literals), len(target.InputTypes))
		}
		literals := append([]string(nil), seed.Literals...)
		for i, literal := range literals {
			if strings.Contains(literal, "math.") {
				data.NeedsMath = true
				literals[i] = strings.ReplaceAll(literal, "math.", data.Math+".")
			}
		}
		data.Seeds = append(data.Seeds, entry{Name: strconv.Quote(seed.Hash), Literals: literals})
	}
	tmpl, err := template.New("harness").Funcs(template.FuncMap{"join": strings.Join}).Parse(harnessTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	code, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated harness: %w", err)
	}
	return code, nil
}

func supportedInputType(inputType string) bool {
	switch inputType {
	case "string", "[]byte", "bool", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64":
		return true
	}
	return false
}
